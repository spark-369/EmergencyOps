package com.pstu.backend.entity;

import com.pstu.backend.enums.IncidentSeverity;
import com.pstu.backend.enums.IncidentStatus;
import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.EqualsAndHashCode;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import lombok.ToString;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;

import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;

/**
 * An emergency incident.
 *
 * <p>{@code @Getter}/{@code @Setter} are used instead of {@code @Data}: the
 * generated `equals`/`hashCode`/`toString` would otherwise include `allocations`,
 * initialising a lazy collection (an extra query, or a
 * `LazyInitializationException` outside a transaction) and recursing through the
 * bidirectional association with `ResourceAllocation.incident`. Equality is
 * therefore based on the identity columns only, and `allocations` is excluded
 * from both `equals`/`hashCode` and `toString`.
 */
@Entity
@Table(
        name = "emergency_incidents",
        // `findByIncidentId` returns Optional/uses it as a unique key in five
        // services, so the business id must be unique in the database too.
        uniqueConstraints = @UniqueConstraint(
                name = "uk_emergency_incidents_incident_id",
                columnNames = "incidentId"
        ),
        indexes = {
                // Powers findActiveIncidentsByStatuses(...), which orders by
                // priorityScore DESC, createdAt ASC.
                @Index(name = "idx_emergency_incidents_status_priority", columnList = "status, priorityScore"),
                // Powers findIncidentsInRegion(...).
                @Index(name = "idx_emergency_incidents_location", columnList = "latitude, longitude")
        }
)
@Getter
@Setter
@Builder
@NoArgsConstructor
@AllArgsConstructor
@ToString(onlyExplicitlyIncluded = true)
@EqualsAndHashCode(onlyExplicitlyIncluded = true)
public class EmergencyIncident {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @EqualsAndHashCode.Include
    @ToString.Include
    private Long id;

    /**
     * Business identifier (UUID). Generated by IncidentService; never
     * client-supplied. Immutable once persisted, hence `updatable = false`.
     * Uniqueness is declared once, as the named constraint on {@link Table}.
     */
    @Column(nullable = false, length = 64, updatable = false)
    @ToString.Include
    private String incidentId;

    @Column(nullable = false)
    private Double latitude;

    @Column(nullable = false)
    private Double longitude;

    @Column(nullable = false, length = 500)
    private String locationDescription;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 32)
    private IncidentSeverity severity;

    @Column(nullable = false)
    private Integer affectedPeople;

    @Column(nullable = false)
    private Integer timeSensitivityMinutes;

    /**
     * Structured requirements / conditions, stored as a JSON column.
     *
     * <p>{@code @JdbcTypeCode(SqlTypes.JSON)} lets Hibernate pick the dialect's
     * JSON type — {@code jsonb} on PostgreSQL, native JSON on H2 — instead of the
     * hard-coded {@code columnDefinition = "jsonb"} this used to carry, which made
     * the schema impossible to create outside PostgreSQL.
     */
    @JdbcTypeCode(SqlTypes.JSON)
    private Map<String, Object> resourceRequirements;

    @JdbcTypeCode(SqlTypes.JSON)
    private Map<String, Object> environmentalConditions;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 32)
    private IncidentStatus status;

    @Column(nullable = false)
    private Integer priorityScore;

    @Column(nullable = false)
    private Integer estimatedResponseTimeMinutes;

    @CreationTimestamp
    @Column(nullable = false, updatable = false)
    private LocalDateTime createdAt;

    @UpdateTimestamp
    @Column(nullable = false)
    private LocalDateTime updatedAt;

    /**
     * Deployments attached to this incident.
     *
     * <p>Excluded from `toString`/`equals`/`hashCode` automatically, because both
     * are generated with {@code onlyExplicitlyIncluded = true} on the class.
     * Including this collection would initialise it lazily and recurse through
     * {@code ResourceAllocation.incident}.
     */
    @OneToMany(mappedBy = "incident", cascade = CascadeType.ALL, orphanRemoval = true, fetch = FetchType.LAZY)
    @Builder.Default
    private List<ResourceAllocation> allocations = new ArrayList<>();
}